// Generates design-system/plex.css — IBM Plex (latin subset, woff2, base64) so the
// design-system cards render in the REAL typeface with no network dependency.
//
// Why this exists: the cards originally pulled Plex from Google Fonts with a
// <link>. If that request is blocked or slow in the viewer, every card silently
// falls back to system-ui — which means the type decision was being reviewed
// against a font nobody chose. Embedding removes the question.
//
//   node tools/bundle-plex.mjs
//
// Kept to the four faces the cards actually use, to keep the file small.
import { writeFile } from 'node:fs/promises';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

const FACES = [
  { family: 'IBM Plex Sans',            weight: 400 },
  { family: 'IBM Plex Sans',            weight: 600 },
  { family: 'IBM Plex Sans Condensed',  weight: 700 },
  { family: 'IBM Plex Mono',            weight: 500 },
];

const blocks = [];
let total = 0;
for (const { family, weight } of FACES) {
  const cssUrl = `https://fonts.googleapis.com/css2?family=${family.replace(/ /g, '+')}:wght@${weight}`;
  const css = await (await fetch(cssUrl, { headers: { 'User-Agent': UA } })).text();
  const m = /\/\*\s*latin\s*\*\/\s*@font-face\s*\{([^}]*)\}/.exec(css);
  if (!m) throw new Error(`no /* latin */ @font-face for ${family} ${weight}`);
  const url = m[1].match(/url\((https:\/\/[^)]+\.woff2)\)/);
  if (!url) throw new Error(`no woff2 url for ${family} ${weight}`);
  const buf = Buffer.from(await (await fetch(url[1], { headers: { 'User-Agent': UA } })).arrayBuffer());
  total += buf.length;
  blocks.push(`@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${buf.toString('base64')}) format('woff2')}`);
  console.error(`  ${family} ${weight}: ${buf.length} bytes`);
}
console.error(`  total raw: ${(total / 1024).toFixed(1)} KB`);

await writeFile('design-system/plex.css',
  `/* GENERATED by tools/bundle-plex.mjs — IBM Plex latin subset, base64.\n   The design-system cards embed this so type is reviewed in the REAL face,\n   never in a silent system fallback. Do not hand-edit. */\n${blocks.join('\n')}\n`);
console.error('wrote design-system/plex.css');
