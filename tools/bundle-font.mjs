// Bundles a Google font (latin subset, woff2) into css/fonts.css as a base64
// @font-face data-URI, so the single-file offline build ships the display type
// with zero network calls (the brief's hard constraint). Re-run to regenerate.
//
//   node tools/bundle-font.mjs
//
// Keep the family in sync with the @font-face consumers in css/styles.css.
import { writeFile } from 'node:fs/promises';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';
const FAMILY = 'Barlow Condensed';
const WEIGHTS = [600, 700];

const blocks = [];
for (const w of WEIGHTS) {
  const cssUrl = `https://fonts.googleapis.com/css2?family=${FAMILY.replace(/ /g, '+')}:wght@${w}`;
  const css = await (await fetch(cssUrl, { headers: { 'User-Agent': UA } })).text();
  // Google emits one @font-face per subset, each preceded by a /* subset */ comment.
  // Grab the basic `/* latin */` block (not latin-ext) — enough for English film data.
  const m = /\/\*\s*latin\s*\*\/\s*@font-face\s*\{([^}]*)\}/.exec(css);
  if (!m) throw new Error(`no /* latin */ @font-face for weight ${w}`);
  const url = m[1].match(/url\((https:\/\/[^)]+\.woff2)\)/);
  if (!url) throw new Error(`no woff2 url for weight ${w}`);
  const buf = Buffer.from(await (await fetch(url[1], { headers: { 'User-Agent': UA } })).arrayBuffer());
  const b64 = buf.toString('base64');
  blocks.push(`@font-face{font-family:'${FAMILY}';font-style:normal;font-weight:${w};font-display:swap;src:url(data:font/woff2;base64,${b64}) format('woff2');}`);
  console.error(`  ${FAMILY} ${w}: ${buf.length} bytes raw -> ${b64.length} b64 chars`);
}

const out = `/* GENERATED by tools/bundle-font.mjs — ${FAMILY} (latin subset, base64) so the\n   stats-dashboard display type ships offline in the single-file build. Do not hand-edit. */\n${blocks.join('\n')}\n`;
await writeFile(new URL('../css/fonts.css', import.meta.url), out, 'utf8');
console.error(`wrote css/fonts.css (${out.length} bytes)`);
